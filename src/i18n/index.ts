const CATALOGS: Record<Locale, Record<string, string>> = { en: EN, zh: ZH }
const LOCALE_KEY = 'forgeax.locale'
const LOCALE_MSG = 'forgeax:locale-changed'
const listeners = new Set<() => void>()
let current: Locale = 'en'
let wired = false

export function getLocale(): Locale {
  return current
}

export function setLocale(next: Locale): void {
  if (next === current) return
  current = next
  try {
    document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
  } catch { /* SSR */ }
  for (const listener of listeners) listener()
}

function parseLocale(raw: unknown): Locale | null {
  if (typeof raw !== 'string') return null
  const normalized = raw.trim().toLowerCase().replaceAll('_', '-')
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh'
  return null
}

/** Browser/OS default: use the first supported language, then fall back to English. */
export function detectSystemLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en'
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const lang of langs) {
    const parsed = parseLocale(lang)
    if (parsed) return parsed
  }
  return 'en'
}

function readInitialLocale(fallback: Locale): Locale {
  try {
    const params = new URLSearchParams(location.search)
    // Studio iframe uses `locale=zh`; Zaohua published pages often use `lang=zh-CN`.
    const fromUrl = parseLocale(params.get('locale')) ?? parseLocale(params.get('lang'))
    if (fromUrl) return fromUrl
  } catch { /* SSR */ }
  try {
    const stored = parseLocale(localStorage.getItem(LOCALE_KEY))
    if (stored) return stored
  } catch { /* private mode */ }
  return fallback
}

/** `initialLocale` is a host-supplied override and wins outright. `fallback`
 *  only applies when neither the URL nor storage expresses a preference. */
export function initLocaleSync(initialLocale?: Locale, fallback: Locale = 'en'): void {
  setLocale(initialLocale ?? readInitialLocale(fallback))
  if (wired || typeof window === 'undefined') return
  wired = true
  window.addEventListener('storage', (event) => {
    if (event.key !== LOCALE_KEY) return
    const next = parseLocale(event.newValue)
    if (next) setLocale(next)
  })
  window.addEventListener('message', (event) => {
    const data = event.data as { type?: string; locale?: string } | null
    if (data?.type !== LOCALE_MSG) return
    const next = parseLocale(data.locale)
    if (next) setLocale(next)
  })
}

export function onLocaleChange(listener: () => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

export function t(key: string): string {
  return CATALOGS[current][key] ?? EN[key] ?? key
}

export function tf(key: string, vars: Record<string, string | number>): string {
  let message = t(key)
  for (const [name, value] of Object.entries(vars)) {
    message = message.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value))
  }
  return message
}

export function useT(): typeof t {
  useLocale()
  return t
}

export function useLocale(): Locale {
  return useSyncExternalStore(onLocaleChange, getLocale, getLocale)
}
